"use client";

import { useMemo } from "react";
import { format } from "date-fns";
import { Eye } from "lucide-react";
import type { ShareSnapshot } from "@/lib/share";
import type { ClientMessage } from "@/server/agent/serialize";
import { AssistantMessage, UserMessage } from "@/components/chat/message";
import { MessageViewCtx, type MessageViewContext } from "@/components/chat/view-context";
import { useMounted } from "@/hooks/use-mounted";

const noop = async () => {};

/** Read-only rendering of a share snapshot. */
export function SharedThread({ token, snapshot }: { token: string; snapshot: ShareSnapshot }) {
  const mounted = useMounted();
  const view = useMemo<MessageViewContext>(
    () => ({
      readOnly: true,
      attachmentUrl: (id) => `/api/share/${encodeURIComponent(token)}/attachments/${encodeURIComponent(id)}`,
    }),
    [token],
  );
  const messages: ClientMessage[] = useMemo(
    () =>
      snapshot.messages.map((m) => ({
        id: m.id,
        parentId: null,
        compareGroupId: null,
        role: m.role,
        parts: m.parts,
        modelId: m.modelId,
        effort: null,
        webSearch: false,
        status: m.status,
        error: null,
        createdAt: m.createdAt,
        usage: null,
      })),
    [snapshot],
  );
  const names = new Map(snapshot.messages.map((m) => [m.id, m.modelName]));
  const lastId = messages.at(-1)?.id;

  return (
    <MessageViewCtx value={view}>
      <header className="sticky top-0 z-10 border-b bg-background/90 backdrop-blur">
        <div className="mx-auto flex max-w-3xl items-center gap-3 px-4 py-3 sm:px-6">
          <span className="text-sm font-semibold tracking-tight">Obot</span>
          <span className="min-w-0 flex-1 truncate text-sm text-muted-foreground">{snapshot.title}</span>
          <span className="inline-flex shrink-0 items-center gap-1 rounded-full border px-2 py-0.5 text-[11px] text-muted-foreground">
            <Eye className="size-3" /> Read-only
          </span>
        </div>
      </header>
      <main className="mx-auto flex max-w-3xl flex-col gap-8 px-4 pt-8 pb-16 sm:px-6">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">{snapshot.title}</h1>
          <p className="mt-1 text-xs text-muted-foreground">
            Shared conversation{mounted ? ` · ${format(new Date(snapshot.sharedAt), "PPP")}` : ""}
          </p>
        </div>
        {messages.map((m) =>
          m.role === "USER" ? (
            <UserMessage key={m.id} message={m} canEdit={false} onEdit={noop} />
          ) : (
            <AssistantMessage
              key={m.id}
              message={m}
              modelName={names.get(m.id) ?? null}
              canRegenerate={false}
              isLast={m.id === lastId}
              onRegenerate={() => {}}
            />
          ),
        )}
        <p className="border-t pt-6 text-center text-xs text-muted-foreground">
          A snapshot shared from Obot. Replies were generated by AI and may contain mistakes.
        </p>
      </main>
    </MessageViewCtx>
  );
}
